"""Regression: the generated catalogs must stay OUT of the recall hot path.

`index.md` and `log.md` are navigation aids, not knowledge. Retrieval in this
provider is FTS5 (+ optional embeddings), so the LLM-wiki pattern's
"read the index first" step would be a regression here: it would let a page
that merely *lists* every title outrank the page that actually holds the
answer. These tests lock in that boundary.
"""

from __future__ import annotations

import tempfile
import unittest
from pathlib import Path

import _hwiki_path  # noqa: F401,E402

from hwiki.catalog import (  # noqa: E402
    INDEX_FILENAME,
    LOG_FILENAME,
    append_log,
    write_index,
)
from hwiki.search import Fts5Backend, RankingPartitionBackend  # noqa: E402
from hwiki.store import WikiStore  # noqa: E402


def _wiki(root: Path) -> WikiStore:
    (root / "concepts").mkdir(parents=True, exist_ok=True)
    (root / "concepts" / "retrieval.md").write_text(
        "---\ntitle: Retrieval\n---\n\n# Retrieval\n\n"
        "Hybrid search blends lexical and vector recall for memory lookup.\n",
        encoding="utf-8",
    )
    (root / "concepts" / "honcho.md").write_text(
        "---\ntitle: Honcho\n---\n\n# Honcho\n\n"
        "Honcho derives facts from conversation transcripts.\n",
        encoding="utf-8",
    )
    return WikiStore(root, include=["**/*.md"], memory_dir="memory/auto")


class CatalogRecallBoundaryTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self.store = _wiki(self.root)
        self.db = self.root / "index.sqlite"
        self.fts = Fts5Backend(self.store, db_path=self.db)
        self.fts.sync(force=True)

    def tearDown(self):
        try:
            self.fts.close()
        except Exception:
            pass
        self.tmp.cleanup()

    def _ranking(self) -> RankingPartitionBackend:
        return RankingPartitionBackend(
            self.fts, max_hits_per_page=2,
            demote_paths=[LOG_FILENAME, INDEX_FILENAME], fetch_multiplier=4,
        )

    def test_index_page_does_not_outrank_curated_page(self):
        write_index(self.store, memory_dir="memory/auto")
        self.fts.sync(force=True)
        hits = self._ranking().search("hybrid search vector recall", limit=3)
        paths = [h.path for h in hits]
        self.assertTrue(paths, "expected hits")
        self.assertEqual(paths[0], "concepts/retrieval.md", paths)
        if INDEX_FILENAME in paths:
            self.assertEqual(paths[-1], INDEX_FILENAME,
                             f"index must be demoted, got {paths}")

    def test_query_matching_only_index_boilerplate_is_demoted(self):
        write_index(self.store, memory_dir="memory/auto")
        self.fts.sync(force=True)
        hits = self._ranking().search(
            "generated by the hwiki memory provider from the pages on disk", limit=4)
        paths = [h.path for h in hits]
        if paths:
            self.assertNotEqual(paths[0], INDEX_FILENAME, paths)

    def test_log_entries_demoted_but_reachable(self):
        append_log(self.store, "write", "Prefers dark mode",
                   detail="hybrid search note recorded for recall lookup")
        self.fts.sync(force=True)
        hits = self._ranking().search("hybrid search vector recall", limit=3)
        paths = [h.path for h in hits]
        self.assertEqual(paths[0], "concepts/retrieval.md", paths)
        only_log = self._ranking().search("prefers dark mode recorded", limit=3)
        self.assertTrue(any(h.path == LOG_FILENAME for h in only_log),
                        [h.path for h in only_log])

    def test_catalogs_live_outside_memory_zone(self):
        write_index(self.store, memory_dir="memory/auto")
        append_log(self.store, "write", "x")
        memory_zone = self.root / "memory" / "auto"
        self.assertFalse((memory_zone / INDEX_FILENAME).exists())
        self.assertFalse((memory_zone / LOG_FILENAME).exists())
        self.assertTrue((self.root / INDEX_FILENAME).exists())
        self.assertTrue((self.root / LOG_FILENAME).exists())


if __name__ == "__main__":
    unittest.main(verbosity=2)
