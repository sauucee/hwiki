"""Generated metric blocks for vault pages.

Prose metrics rot. Every hand-written measurement in this vault went stale within a
day: ``HANDOFF.md`` said "183/225" long after those figures moved, and the hwiki
pages claimed "16 pages / 88 chunks" the moment two more pages existed. Writing
fresher numbers and promising to keep them current is not a fix — it is the same
thing that failed both times.

So metrics move into a block that automation owns:

    <!-- hwiki:stats:start -->
    ...
    <!-- hwiki:stats:end -->

Same contract as ``compile``'s merged sections (``compile.SECTION_START``): the
generator only ever replaces what sits between the markers, hand-written prose on
either side is byte-identical afterwards, and a page with no markers is never
touched. A page that wants live numbers opts in by adding the empty markers once.

Two rules that matter more than the formatting:

* **Never invent a number.** A value that could not be measured renders as
  ``unknown``, not ``0``. A zero is a claim; "unknown" is the truth.
* **Deterministic.** The same vault state must render byte-identical output so a
  no-op tick writes nothing and git stays quiet.
"""

from __future__ import annotations

import logging
import re
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, Optional

logger = logging.getLogger(__name__)

STATS_START = "<!-- hwiki:stats:start -->"
STATS_END = "<!-- hwiki:stats:end -->"

_BLOCK_RE = re.compile(
    re.escape(STATS_START) + r".*?" + re.escape(STATS_END), re.DOTALL)

#: A reader must be able to reproduce every figure, so the block names its source.
PRODUCING_COMMAND = "hermes hwiki status"


def _cell(value: Any) -> str:
    """Render one measured value. ``None`` is 'unknown', never a zero."""
    if value is None:
        return "unknown"
    if isinstance(value, bool):  # bool is an int subclass; keep it explicit
        return "yes" if value else "no"
    if isinstance(value, int):
        return str(value)
    text = str(value).strip()
    return text or "unknown"


def render_stats_block(*, pages: Optional[int] = None,
                       chunks: Optional[int] = None,
                       facts: Optional[int] = None,
                       tip: Optional[str] = None,
                       tests: Optional[int] = None,
                       generated_at: str = "") -> str:
    """Render the delimited stats block.

    Every argument is optional on purpose: a caller that could not measure a value
    passes ``None`` and the block says ``unknown``. Passing a guess is the one thing
    this module exists to prevent.
    """
    rows = [
        ("indexed pages", _cell(pages)),
        ("indexed chunks", _cell(chunks)),
        ("accepted facts", _cell(facts)),
        ("plugin tip", f"`{_cell(tip)}`" if tip else "unknown"),
        ("tests passing", _cell(tests)),
    ]
    lines = [STATS_START, "", "| metric | value |", "| --- | --- |"]
    lines += [f"| {name} | {value} |" for name, value in rows]
    lines.append("")
    note = f"*Generated by `hwiki`; a tick rewrites this block. `{PRODUCING_COMMAND}`"
    if generated_at:
        note += f" · {generated_at}"
    lines += [note + ".*", "", STATS_END]
    return "\n".join(lines)


def replace_stats_block(text: str, block: str) -> str:
    """Replace every generated block in ``text``. No markers means no change.

    A page without markers is hand-written: adding a generated block to it would be
    an unrequested edit, so this returns the text untouched.
    """
    if STATS_START not in text:
        return text
    return _BLOCK_RE.sub(lambda _match: block, text)


def has_stats_block(text: str) -> bool:
    return STATS_START in (text or "") and STATS_END in (text or "")


def measure_stats(vault_root: Path, *, memory_rel: Path,
                  repo_dir: Optional[Path] = None,
                  store: Any = None,
                  backend: Any = None,
                  run_tests: bool = False,
                  timeout_s: int = 300) -> Dict[str, Any]:
    """Measure what is cheaply available; ``None`` for what is not.

    Prefers the live provider objects when given one, because they are the authority:
    ``store`` knows how many facts are actually *accepted* (not just how many files
    sit in the memory directory) and ``backend`` knows the index's real page and
    chunk counts. Disk counting is the fallback, and it is deliberately labelled a
    fallback — a file count is not a fact count.

    Anything unavailable stays ``None`` rather than becoming a plausible-looking
    number. A test run is minutes, not milliseconds, so it happens only on request.
    """
    vault_root = Path(vault_root)
    stats: Dict[str, Any] = {"pages": None, "chunks": None, "facts": None,
                             "tip": None, "tests": None}

    # -- index counts, from the backend when available ------------------------
    if backend is not None and hasattr(backend, "count"):
        try:
            counts = backend.count() or {}
            stats["pages"] = counts.get("pages")
            stats["chunks"] = counts.get("chunks")
        except Exception as exc:  # noqa: BLE001 - a stats block must never break a tick
            logger.info("stats: backend count unavailable: %s", exc)

    if stats["pages"] is None:
        # Fallback: count markdown that could be corpus. Every generated artifact is
        # excluded — the catalog pair, the maintenance report, and any page carrying
        # a stats block. Writing those changes the file, and counting them would make
        # the count depend on whether this very job had already run, so it could
        # never settle (measured 1 -> 2 -> 2 before the exclusion).
        try:
            if vault_root.is_dir():
                pages = []
                for candidate in vault_root.rglob("*.md"):
                    if not candidate.is_file():
                        continue
                    if candidate.name in ("index.md", "log.md", "maintenance.md"):
                        continue
                    try:
                        if STATS_START in candidate.read_text(
                                encoding="utf-8", errors="replace"):
                            continue  # a generated-report page is not corpus
                    except OSError:
                        continue
                    pages.append(candidate)
                stats["pages"] = len(pages)
        except OSError:
            pass

    # -- accepted facts, from the store when available -----------------------
    if store is not None and hasattr(store, "list_proposals"):
        try:
            stats["facts"] = len(store.list_proposals(status="accepted",
                                                      limit=100000))
        except Exception as exc:  # noqa: BLE001
            logger.info("stats: could not count accepted facts: %s", exc)
    if stats["facts"] is None:
        try:
            memory_dir = Path(vault_root) / memory_rel
            if memory_dir.is_dir():
                # The maintenance report lives in this directory and is written by
                # the tick that calls this function, so it must not count as a fact.
                stats["facts"] = len([
                    p for p in memory_dir.glob("*.md")
                    if p.is_file() and p.name != "maintenance.md"])
        except OSError:
            pass

    if repo_dir is not None:
        try:
            out = subprocess.run(
                ["git", "-C", str(repo_dir), "rev-parse", "--short", "HEAD"],
                capture_output=True, text=True, timeout=10)
            if out.returncode == 0 and out.stdout.strip():
                stats["tip"] = out.stdout.strip()
        except (OSError, subprocess.SubprocessError) as exc:
            logger.info("stats: could not read the plugin tip: %s", exc)

    if run_tests and repo_dir is not None:
        # Use the interpreter that can actually import pytest, and never report a
        # count we did not observe. Running `python3 -m pytest` here silently failed
        # (system python has no pytest) while the block kept showing an old passing
        # number — the precise staleness this module exists to remove. So: try the
        # running interpreter, then the known pytest shim, and if neither works the
        # count stays unknown.
        for interpreter in _test_interpreters():
            try:
                out = subprocess.run(
                    [interpreter, "-m", "pytest", "tests/", "-q"],
                    cwd=str(repo_dir), capture_output=True, text=True,
                    timeout=timeout_s)
            except (OSError, subprocess.SubprocessError) as exc:
                logger.info("stats: %s could not run tests: %s", interpreter, exc)
                continue
            match = re.search(r"(\d+) passed", out.stdout or "")
            if match:
                stats["tests"] = int(match.group(1))
                break
            logger.info("stats: %s produced no passing count (exit %s): %s",
                        interpreter, out.returncode,
                        (out.stderr or "").strip()[-200:])

    return stats


def _test_interpreters() -> list:
    """Interpreters worth trying for the test count, most-likely first.

    System ``python3`` may have no pytest at all, in which case the run produces no
    count and the block says ``unknown`` rather than repeating an old figure.
    """
    candidates = [sys.executable]
    shim = Path.home() / ".local" / "bin" / "pytest"
    try:
        if shim.is_file():
            first = shim.read_text(encoding="utf-8", errors="replace").splitlines()[:1]
            if first and first[0].startswith("#!"):
                candidates.append(first[0][2:].strip())
    except OSError:
        pass
    seen, ordered = set(), []
    for candidate in candidates:
        if candidate and candidate not in seen:
            seen.add(candidate)
            ordered.append(candidate)
    return ordered
